# parses the code generated by linearmod2
def parse():
    with open("test.c", "r") as f:
        lines = f.readlines()

    # find the main
    code = ""
    for i in range(len(lines)):
        if "main" in lines[i]:
            code = lines[i + 4:-9]
            break
    code = [line.strip()[:-2].replace('(', ',').split(',') for line in code]

    return code


